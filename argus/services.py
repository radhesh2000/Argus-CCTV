# install / uninstall
# --------------------------------------------------------------------------


def install(config: ArgusConfig, *, root: Path | None = None,
            with_vlm: bool = False, enable: bool = True, start: bool = False,
            dry_run: bool = False, directory: Path | None = None,
            command: Sequence[str] | None = None,
            runner: Runner | None = None) -> dict[str, Any]:
    """Write the units, reload, and (by default) enable them.

    Idempotent in the way that matters: a unit whose text is already correct is
    left alone and reported ``unchanged``, so re-running the installer does not
    churn mtimes or force a daemon-reload that restarts nothing.
    """
    base = Path(root or ROOT)
    target_dir = Path(directory) if directory is not None else unit_dir()
    run = runner or _default_runner
    units = render(config, root=base, command=command)

    result: dict[str, Any] = {
        "directory": str(target_dir),
        "units": [],
        "enabled": [],
        "started": [],
        "commands": [],
        "dry_run": dry_run,
    }

    for unit in units:
        path = target_dir / unit.name
        existing = path.read_text() if path.is_file() else None
        if existing == unit.text:
            action = "unchanged"
        elif existing is None:
            action = "written"
        elif GENERATED_MARKER in existing:
            action = "updated"
        else:
            raise ServiceError(
                f"{path} exists and was not written by argus — move it aside first"
            )
        if not dry_run and action != "unchanged":
            target_dir.mkdir(parents=True, exist_ok=True)
            path.write_text(unit.text)
        result["units"].append({"name": unit.name, "path": str(path), "action": action})

    wanted = [u.name for u in units if u.enable_by_default or (with_vlm and u.name == VLM_UNIT)]

    commands: list[list[str]] = [["systemctl", "--user", "daemon-reload"]]
    if enable:
        commands.append(["systemctl", "--user", "enable", *wanted])
    if start:
        commands.append(["systemctl", "--user", "start", TARGET_UNIT])
        if with_vlm:
            commands.append(["systemctl", "--user", "start", VLM_UNIT])

    for argv in commands:
        result["commands"].append(" ".join(argv))
        if dry_run:
            continue
        if not systemctl_available():
            raise ServiceError(
                "systemctl not found — the units were written but nothing was enabled. "
                "This box has no systemd user manager."
            )
        completed = run(argv)
        if completed.returncode != 0:
            raise ServiceError(
                f"{' '.join(argv)} failed ({completed.returncode}): "
                f"{(completed.stderr or completed.stdout or '').strip()}"
            )

    if enable:
        result["enabled"] = wanted
    if start:
        result["started"] = [TARGET_UNIT] + ([VLM_UNIT] if with_vlm else [])
    result["linger"] = linger_enabled(runner=run)
    result["linger_command"] = f"sudo loginctl enable-linger {os.environ.get('USER', '$USER')}"
    return result


def uninstall(*, directory: Path | None = None, dry_run: bool = False,
              runner: Runner | None = None) -> dict[str, Any]:
    """Stop, disable and remove the generated units. Never touches a unit file
    that does not carry the generated marker."""
    target_dir = Path(directory) if directory is not None else unit_dir()
    run = runner or _default_runner
    removed: list[str] = []
    kept: list[str] = []

    present = [name for name in UNIT_NAMES if (target_dir / name).is_file()]
    commands: list[list[str]] = []
    if present:
        commands.append(["systemctl", "--user", "stop", *present])
        commands.append(["systemctl", "--user", "disable", *present])
    for argv in commands:
        if dry_run or not systemctl_available():
            continue
        run(argv)  # a unit that was never started is not an error worth raising

    for name in present:
        path = target_dir / name
        if GENERATED_MARKER not in path.read_text():
            kept.append(str(path))
            continue
        if not dry_run:
            path.unlink()
        removed.append(str(path))

    if not dry_run and systemctl_available():
        run(["systemctl", "--user", "daemon-reload"])
    return {"removed": removed, "kept": kept, "directory": str(target_dir),
            "commands": [" ".join(c) for c in commands], "dry_run": dry_run}


