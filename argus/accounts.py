def roster(db: Database) -> list[dict[str, Any]]:
    """Every account, with its permissions resolved for the console."""
    return [
        {**dict(row), "permissions": sorted(core.permissions_for(str(row["role"])))}
        for row in db.list_users()
    ]


def bootstrap_hint(db: Database) -> str | None:
    """The sentence to show when this appliance has no accounts, or None."""
    if db.count_users() > 0:
        return None
    return ("No accounts on this appliance. Create the first administrator on the box: "
            "`argus user add <name> --role ADMIN`")


