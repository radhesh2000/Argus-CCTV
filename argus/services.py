# rendering
# --------------------------------------------------------------------------


def _environment(config: ArgusConfig, root: Path) -> list[str]:
    lines = [
        # Unbuffered, or journalctl shows nothing until the process dies.
        "Environment=PYTHONUNBUFFERED=1",
        # The claim this product is sold on, enforced at the process boundary:
        # a serving appliance never reaches HuggingFace. Weights are fetched at
        # install time by scripts/fetch_*.sh, and a missing checkpoint becomes a
        # loud failure here rather than a silent download on a plant's uplink.
        "Environment=HF_HUB_OFFLINE=1",
        # RF-DETR's own cache, pointed inside data_dir for the same reason (see
        # argus/vision/detector.py) — it downloads from storage.googleapis.com,
        # which HF_HUB_OFFLINE does not cover, so scripts/fetch_detector.sh
        # pre-stages it and this makes sure both agree where it lives.
        f"Environment=RF_HOME={config.models_dir}",
    ]
    if config.source_path is not None:
        lines.insert(0, f"Environment=ARGUS_CONFIG={config.source_path}")
    else:
        lines.insert(0, f"Environment=ARGUS_CONFIG={root / 'config' / 'argus.yaml'}")
    return lines


def _header(description: str, root: Path) -> list[str]:
    return [
        GENERATED_MARKER,
        f"# {root}",
        "",
        "[Unit]",
        f"Description={description}",
        f"Documentation=file://{root / 'docs' / 'INSTALL.md'}",
    ]


def render(config: ArgusConfig, *, root: Path | None = None,
           command: Sequence[str] | None = None) -> list[Unit]:
    """Every unit, as text. Pure — no filesystem, no systemctl."""
    base = Path(root or ROOT)
    argv = list(command) if command else argus_command(base)
    env = _environment(config, base)

    engine = [
        *_header("Argus vision engine — decode, detect, track, evidence", base),
        # Stop and restart with the appliance as a whole, but start alone too.
        f"PartOf={TARGET_UNIT}",
        "",
        "[Service]",
        "Type=simple",
        f"WorkingDirectory={base}",
        *env,
        # The pause switch, enforced at start time. Exits 0 when processing is
        # enabled and 1 when it is not; on a 1 systemd skips the start *cleanly*
        # (no ExecStart, unit stays inactive, not failed), so a rebooted or
        # `restart argus.target`-ed appliance that was paused comes up paused
        # with the GPU idle. See argus/processing.py.
        f"ExecCondition={_quote([*argv, 'processing', 'gate'])}",
        f"ExecStart={_quote([*argv, 'run'])}",
        # always, not on-failure: a camera fleet that stopped because the
        # engine exited 0 on an unhandled shutdown path is still an outage.
        "Restart=always",
        "RestartSec=5",
        # The engine handles SIGTERM: it stops decoders, ffmpeg children, the
        # ring recorder and the gateway. 45 s is generous for that and still
        # bounded, so a wedged shutdown does not hang a reboot forever.
        "KillSignal=SIGTERM",
        "TimeoutStopSec=45",
        "SyslogIdentifier=argus-engine",
        "StandardOutput=journal",
        "StandardError=journal",
        "",
        "[Install]",
        f"WantedBy={TARGET_UNIT}",
    ]

    api = [
        *_header("Argus API and operator console", base),
        f"PartOf={TARGET_UNIT}",
        # Ordering only, no Wants: the console is designed to come up without
        # the engine and say so. This exists so that when both start together
        # the engine wins the race to apply a pending schema migration.
        f"After={ENGINE_UNIT}",
        "",
        "[Service]",
        "Type=simple",
        f"WorkingDirectory={base}",
        *env,
        f"ExecStart={_quote([*argv, 'api'])}",
        "Restart=always",
        "RestartSec=5",
        "TimeoutStopSec=20",
        "SyslogIdentifier=argus-api",
        "StandardOutput=journal",
        "StandardError=journal",
        "",
        "[Install]",
        f"WantedBy={TARGET_UNIT}",
    ]

    from argus.vlm.server import paths_for  # light: stdlib + config only

    startup = int(max(120.0, config.vlm.server.startup_timeout_sec))
    vlm = [
        *_header("Argus VLM inference server (optional)", base),
        f"PartOf={TARGET_UNIT}",
        # A model that crashes on load crashes the same way every time, and
        # restarting it costs minutes of GPU. Three tries in half an hour, then
        # it stays down and `argus vlm health` explains why.
        "StartLimitIntervalSec=1800",
        "StartLimitBurst=3",
        "",
        "[Service]",
        # forking + PIDFile: `argus vlm start` waits for the model to answer
        # before it returns, so `systemctl start` means "serving", not "spawned".
        "Type=forking",
        f"PIDFile={paths_for(config).pidfile}",
        f"WorkingDirectory={base}",
        *env,
        # Same pause gate as the engine: a paused appliance never loads the
        # model, however the unit came to be started. See argus/processing.py.
        f"ExecCondition={_quote([*argv, 'processing', 'gate'])}",
        f"ExecStart={_quote([*argv, 'vlm', 'start'])}",
        f"ExecStop={_quote([*argv, 'vlm', 'stop'])}",
        # Model load is minutes on a cold page cache; the default 90 s would
        # kill it mid-load and call it a failure.
        f"TimeoutStartSec={startup}",
        "TimeoutStopSec=60",
        "Restart=on-failure",
        "RestartSec=30",
        "SyslogIdentifier=argus-vlm",
        "StandardOutput=journal",
        "StandardError=journal",
        "",
        "[Install]",
        f"WantedBy={TARGET_UNIT}",
    ]

    target = [
        GENERATED_MARKER,
        f"# {base}",
        "",
        "[Unit]",
        "Description=Argus appliance",
        f"Documentation=file://{base / 'docs' / 'INSTALL.md'}",
        # One handle for the whole box: `systemctl --user restart argus.target`.
        # The services are pulled in by their own [Install] WantedBy, so what is
        # enabled is what runs — the VLM appears here only if it was enabled.
        "",
        "[Install]",
        "WantedBy=default.target",
    ]

    return [
        Unit(TARGET_UNIT, "\n".join(target) + "\n"),
        Unit(ENGINE_UNIT, "\n".join(engine) + "\n"),
        Unit(API_UNIT, "\n".join(api) + "\n"),
        Unit(VLM_UNIT, "\n".join(vlm) + "\n", enable_by_default=False),
    ]


