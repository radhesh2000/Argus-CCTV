"""systemd **user** units, generated from this appliance's own paths.

``argus install-services`` writes three services and a target into
``~/.config/systemd/user`` and enables them. It assumes no root, and that is
the whole design constraint rather than a nicety: the vLLM environment is
already built by a non-privileged user (``scripts/setup_vlm_server.sh`` says
why), the box's operator may not have sudo, and an installer that needs root is
an installer that gets run as root.

What the user manager costs, said plainly
-----------------------------------------
* **Linger must be enabled or the appliance stops at logout.** ``systemd
  --user`` shuts a user's units down when their last session ends, so a box
  that is meant to run unattended needs ``sudo loginctl enable-linger <user>``
  — the one command here that does need root. It is printed rather than
  attempted, and ``argus doctor`` fails when it is off, because "the cameras
  stopped when I closed the SSH window" is otherwise a mystery.
* **There is no network target to order against.** ``network-online.target``
  belongs to the system manager; a user unit cannot wait for it. Nothing here
  tries: the engine already reconnects to a camera with backoff and the gateway
  supervisor restarts go2rtc, so "started before the NIC was up" is a few
  seconds of retry rather than a failure. ``Restart=always`` is the backstop.

Unit shape, and the two decisions inside it
-------------------------------------------
* **The VLM unit is ``Type=forking``**, driving ``argus vlm start`` / ``stop``
  rather than exec'ing vLLM directly. Those commands already know the venv, the
  weights path, the arguments and — the part that matters to systemd — how to
  wait for the model to answer before reporting success. ``systemctl --user
  start argus-vlm`` therefore returns when the model is *serving*, not when the
  process has been spawned, and a failed load is a failed unit. The alternative
  was a second copy of ``build_command`` inside an ``ExecStart=`` line, which
  would drift from the config the first time somebody changed a flag.
* **``ExecStart`` is an absolute path to this checkout's own ``argus``**, not
  ``uv run``. ``uv run`` re-resolves the environment on every start; a service
  manager restarting a crashed engine at 03:00 must not be able to reach for a
  package index. ``uv run`` is the fallback only when there is no venv script,
  and ``--offline`` is passed even then.

Nothing here imports ``systemd``. Rendering a unit is a pure function of
config, so the units are testable — and tested — on a machine with no systemd
at all; only :func:`install` and :func:`states` shell out to ``systemctl``.
"""

from __future__ import annotations

import os
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Sequence

from argus.config import ROOT, ArgusConfig

ENGINE_UNIT = "argus-engine.service"
API_UNIT = "argus-api.service"
VLM_UNIT = "argus-vlm.service"
TARGET_UNIT = "argus.target"

#: Every unit this module owns, in dependency order. `argus-vlm.service` is
#: written but never enabled by default — the appliance runs without a VLM and
#: the model claims 30% of the box's memory when it does not.
UNIT_NAMES = (TARGET_UNIT, ENGINE_UNIT, API_UNIT, VLM_UNIT)

#: Marks a file as ours, so `install` may overwrite it and `uninstall` may
#: delete it without ever touching a unit somebody wrote by hand.
GENERATED_MARKER = "# Generated by `argus install-services`. Edits are overwritten."

Runner = Callable[[Sequence[str]], "subprocess.CompletedProcess[str]"]


class ServiceError(RuntimeError):
    """Something about the install cannot be done without a person."""


@dataclass(frozen=True, slots=True)
class Unit:
    name: str
    text: str
    #: Enabled by `install()` unless the caller asks otherwise.
    enable_by_default: bool = True

    @property
    def is_service(self) -> bool:
        return self.name.endswith(".service")


# --------------------------------------------------------------------------
# where things live
# --------------------------------------------------------------------------


def unit_dir(env: dict[str, str] | None = None) -> Path:
    """``$XDG_CONFIG_HOME/systemd/user``, honouring the variable if it is set —
    which is what makes this testable in a tmp_path."""
    environ = env if env is not None else dict(os.environ)
    base = environ.get("XDG_CONFIG_HOME") or str(Path(environ.get("HOME", "~")) / ".config")
    return Path(base).expanduser() / "systemd" / "user"


def argus_command(root: Path | None = None) -> list[str]:
    """The argv prefix a unit runs. Absolute, and resolved at install time."""
    base = Path(root or ROOT)
    local = base / ".venv" / "bin" / "argus"
    if local.is_file():
        return [str(local)]
    on_path = shutil.which("argus")
    if on_path:
        return [os.path.realpath(on_path)]
    uv = shutil.which("uv")
    if uv:
        # --offline: a service manager restarting a crashed unit must not be
        # able to reach a package index. If the environment is incomplete the
        # unit should fail loudly at install time, not resolve at 03:00.
        return [uv, "run", "--offline", "--project", str(base), "argus"]
    raise ServiceError(
        f"no argus executable: expected {local}, nothing named argus on PATH, and no uv. "
        "Run `uv sync` first."
    )


def _quote(parts: Sequence[str]) -> str:
    """systemd's ExecStart quoting: only what needs it."""
    out = []
    for part in parts:
        out.append(f'"{part}"' if (" " in part or '"' in part) else part)
    return " ".join(out)


