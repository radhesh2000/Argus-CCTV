"""``evals/labels.yaml`` — the file a human owns.

Everything else in this package is machinery. This is the part where somebody
looks at a frame and says what is in it, and the format is shaped around three
rules that follow from that:

1. **Regenerating never destroys an answer.** ``--build-labels`` merges: new
   frames arrive with null labels, existing frames keep whatever a person wrote,
   and a policy prompt edited by hand survives the next run. A tool that
   silently reset a morning's labelling would be used exactly once.
2. **``null`` means unlabelled and nothing else.** Not "false", not "unknown but
   probably fine". An unlabelled frame is still evaluated and still timed; it is
   simply never scored. Making that the default is what lets the file be
   committed the moment it is generated, before anybody has filled anything in.
3. **Every label says who made it.** ``labelled_by`` is free text and it is not
   decoration: some of the labels in this repository were written by the agent
   that built the harness, by looking at the frames, and a reviewer has to be
   able to tell those from a plant operator's without asking.

The counting slice reads one extra field, ``people``: the number of people
visible in the frame. It is deliberately separate from ``labels``, because it is
not a verdict about a policy — it is a fact about the picture, and it generates
several cases (see ``dataset.py``) rather than one.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

LABELS_VERSION = 1

HEADER = """\
# Argus eval labels — the ground truth `argus eval` scores models against.
#
# Generated by `argus eval --build-labels`, then filled in by a human. Re-running
# --build-labels MERGES: it adds frames it has not seen and never overwrites a
# label, a prompt or a note you have written.
#
# How to fill this in:
#
#   people:  how many people are visible. An integer, or null if you cannot
#            tell. This drives the counting slice — the one that reproduces the
#            failure keeping vlm.verify.enabled false — so it is the single most
#            valuable field in the file.
#   people_exact: true ONLY if you would defend that number against somebody
#            counting alongside you. On a crowded wide shot the honest answer is
#            false, and false still earns the frame its "the claim is wildly
#            wrong" cases — it just cannot supply a "the claim is right" one.
#   labels:  per policy, true if the policy SHOULD fire on this frame, false if
#            it should not, null if you are not sure. null is not a failure:
#            unlabelled frames are still sent and still timed, just not scored.
#   labelled_by: your name, or whatever identifies who made the call.
#   crop:    optional [x1, y1, x2, y2] in 0-1 fractions. A headcount claim in
#            this product is about a ZONE, so a countable sub-region is both
#            more faithful and more labellable than a whole wide shot. Add
#            entries by hand: copy a frame row, give it a new id, add a crop.
#   audit:   optional, per policy: a sentence saying why this one label is
#            doubted and who should settle it. Every run reprints these, so a
#            label a model disagreed with stays a question instead of quietly
#            becoming a score. Delete the line when a human has ruled.
#
# Under `policies:`, each entry may also carry:
#
#   applies_to: optional list of glob patterns matched against frame ids. Absent
#            means "every frame", which is what this file meant before the key
#            existed. Set it and the policy is only asked about the frames it is
#            actually about — a policy about a dispatch bay asked over a packing
#            hall is a case nobody can label, five seconds of GPU, and a row in
#            the disagreements table that crowds out a real one.
#
# Frames themselves live in evals/frames/ and are NOT committed — `source` and
# `ts_sec` below are the recipe, and `sha256` is how you find out if the source
# video changed underneath the labels.
"""


class LabelError(ValueError):
    """The label file could not be read."""


class _BlockDumper(yaml.SafeDumper):
    """A dumper that writes multi-line strings as readable blocks, and no aliases.

    Subclassed rather than registered on ``SafeDumper`` because this process
    also writes other YAML, and a global representer is a side effect on
    somebody else's module.

    **Aliases are off, and that is not cosmetic.** PyYAML emits ``&id001`` /
    ``*id001`` whenever the same object appears twice, which happens the moment
    two frames share a crop rectangle — and the result is a file where editing
    one frame's crop silently edits another's, in a file whose whole purpose is
    to be edited by hand. Repeating four floats is cheaper than that.
    """

    def ignore_aliases(self, data: Any) -> bool:  # noqa: ARG002
        return True


def _represent_str(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    if "\n" in data or len(data) > 90:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


def _represent_list(dumper: yaml.SafeDumper, data: list) -> yaml.SequenceNode:
    """Short all-number lists inline: a crop rectangle is one value, not four.

    ``crop: [0.0, 0.55, 0.4, 1.0]`` is a thing a person can read and edit;
    the same four numbers spread over five lines is a thing they scroll past.
    """
    node = dumper.represent_list(data)
    if data and len(data) <= 8 and all(isinstance(v, (int, float)) for v in data):
        node.flow_style = True
    return node


_BlockDumper.add_representer(str, _represent_str)
_BlockDumper.add_representer(list, _represent_list)


def load(path: Path) -> dict[str, Any]:
    """Read the label file. A missing file is an empty one, not an error."""
    if not path.is_file():
        return {"version": LABELS_VERSION, "policies": {}, "frames": []}
    try:
        data = yaml.safe_load(path.read_text()) or {}
    except yaml.YAMLError as exc:
        raise LabelError(f"{path}: {exc}") from exc
    if not isinstance(data, dict):
        raise LabelError(f"{path}: top level must be a mapping")
    data.setdefault("version", LABELS_VERSION)
    data.setdefault("policies", {})
    data.setdefault("frames", [])
    if not isinstance(data["policies"], dict):
        raise LabelError(f"{path}: 'policies' must be a mapping of key -> {{label, prompt}}")
    if not isinstance(data["frames"], list):
        raise LabelError(f"{path}: 'frames' must be a list")
    return data


def save(path: Path, data: dict[str, Any]) -> None:
    """Write the label file, header comment and all."""
    path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.dump(
        data, Dumper=_BlockDumper, sort_keys=False, allow_unicode=True,
        default_flow_style=False, width=88,
    )
    path.write_text(HEADER + "\n" + body)


def blank_frame_entry(
    frame_id: str, source: str, ts_sec: float, policy_keys: list[str],
    *, sha256: str = "",
) -> dict[str, Any]:
    """A new, unlabelled frame row. Every judgement field is None on purpose."""
    return {
        "id": frame_id,
        "source": source,
        "ts_sec": round(float(ts_sec), 2),
        "sha256": sha256,
        "labelled_by": None,
        "people": None,
        "people_exact": False,
        "labels": {key: None for key in policy_keys},
    }


def merge(
    existing: dict[str, Any],
    frames: list[dict[str, Any]],
    policies: dict[str, dict[str, str]],
) -> tuple[dict[str, Any], int]:
    """Fold newly-sampled frames and policies into an existing label file.

    Returns the merged document and how many frames were added. Nothing a human
    wrote is touched: a policy already present keeps its prompt, a frame already
    present keeps its labels, and a frame that has grown a new policy key gains
    it as null rather than losing the ones it had.
    """
    merged = {
        "version": existing.get("version", LABELS_VERSION),
        "policies": dict(existing.get("policies") or {}),
        "frames": [dict(entry) for entry in existing.get("frames") or []],
    }
    for key, spec in policies.items():
        merged["policies"].setdefault(key, dict(spec))

    policy_keys = list(merged["policies"])
    by_id = {str(entry.get("id")): entry for entry in merged["frames"]}
    added = 0
    for entry in frames:
        identifier = str(entry.get("id"))
        current = by_id.get(identifier)
        if current is None:
            merged["frames"].append(entry)
            by_id[identifier] = entry
            added += 1
            current = entry
        else:
            # Refresh only the derived fields; the labels are not ours to touch.
            for derived in ("source", "ts_sec", "sha256"):
                if entry.get(derived):
                    current[derived] = entry[derived]
        labels = current.setdefault("labels", {})
        for key in policy_keys:
            labels.setdefault(key, None)
        current.setdefault("people", None)
        current.setdefault("people_exact", False)
        current.setdefault("labelled_by", None)

    # Frames that predate a newly-added policy need its key too.
    for entry in merged["frames"]:
        labels = entry.setdefault("labels", {})
        for key in policy_keys:
            labels.setdefault(key, None)

    merged["frames"].sort(key=lambda item: str(item.get("id")))
    return merged, added


def counts(data: dict[str, Any]) -> dict[str, int]:
    """How much of the file a human has actually filled in."""
    frames = data.get("frames") or []
    labelled = sum(
        1 for entry in frames
        if entry.get("people") is not None
        or any(value is not None for value in (entry.get("labels") or {}).values())
    )
    verdicts = sum(
        1 for entry in frames
        for value in (entry.get("labels") or {}).values() if value is not None
    )
    return {
        "frames": len(frames),
        "frames_labelled": labelled,
        "policy_verdicts": verdicts,
        "headcounts": sum(1 for entry in frames if entry.get("people") is not None),
        "policies": len(data.get("policies") or {}),
    }


