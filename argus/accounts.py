@dataclass(slots=True)
class LoginResult:
    principal: core.Principal
    token: str


def rate_limit_state(config: ArgusConfig, db: Database, username: str, ip: str) -> tuple[bool, int]:
    """``(locked, retry_after_seconds)`` for this username and this address.

    Counted on both axes independently and tripped by whichever hits first.
    Username-only would let one attacker lock out the whole plant by spraying
    known operator names; address-only would let a single client walk the roster
    six passwords at a time. See ``Database.failed_login_count``.
    """
    settings = config.auth
    if settings.login_max_attempts <= 0:
        return False, 0
    since = core.iso(core.utcnow() - timedelta(seconds=settings.login_window_sec))
    by_user = db.failed_login_count(since, username=username)
    by_ip = db.failed_login_count(since, ip=ip)
    if max(by_user, by_ip) >= settings.login_max_attempts:
        return True, int(settings.login_lockout_sec)
    return False, 0


def login(config: ArgusConfig, db: Database, username: str, password: str, *,
          ip: str = "unknown", user_agent: str | None = None) -> LoginResult:
    """Verify a password and open a session, or raise.

    Every failure raises the *same* message and status. "No such user", "wrong
    password" and "account disabled" are one answer from outside, because the
    difference between them is a list of who works at this plant. The cost is
    equalised too: a login for a username that does not exist still spends one
    Argon2 verification (:func:`argus.auth.waste_password_time`), so the reply
    time does not leak what the message refuses to.
    """
    try:
        normalized = core.normalize_username(username)
    except ValueError:
        # An unusable username is still an attempt: it must be counted, or the
        # rate limit is bypassed by sending `admin!` instead of `admin`.
        normalized = str(username).strip().lower()[: core.MAX_USERNAME_LENGTH]

    locked, retry_after = rate_limit_state(config, db, normalized, ip)
    if locked:
        raise AccountError(
            f"too many failed sign-in attempts — try again in {retry_after} seconds",
            status=429,
        )

    record = db.credentials_for(normalized)
    if record is None:
        core.waste_password_time()
        _fail(db, normalized, ip)
    if int(record["disabled"] or 0):
        core.waste_password_time()
        _fail(db, normalized, ip)
    if not core.verify_password(str(record["password_hash"]), password):
        _fail(db, normalized, ip)

    # Argon2 parameters change between releases of the library; a login is the
    # only moment the plaintext exists, so it is the only moment a rehash is
    # possible. Doing it here means an appliance upgraded in 2028 re-hashes each
    # account once, on its owner's next sign-in, with nobody having to be told.
    if core.needs_rehash(str(record["password_hash"])):
        db.set_password(int(record["id"]), core.hash_password(password))

    token = core.new_session_token()
    db.create_session(
        core.token_digest(token),
        int(record["id"]),
        core.expiry(config.auth.session_ttl_hours),
        user_agent=(user_agent or "")[:200] or None,
        ip=ip,
    )
    db.note_login(int(record["id"]))
    db.record_login_attempt(normalized, ip, True)
    db.clear_login_failures(normalized, ip)
    _sweep_attempts(config, db)

    session = db.get_session(core.token_digest(token))
    assert session is not None  # just created
    return LoginResult(principal=core.Principal.from_row(session), token=token)


def _fail(db: Database, username: str, ip: str) -> NoReturn:
    db.record_login_attempt(username, ip, False)
    raise AccountError("invalid username or password", status=401)


def _sweep_attempts(config: ArgusConfig, db: Database) -> None:
    """Trim the attempt log on the way past. Cheap, bounded, and it keeps the
    table from being a permanent record of everyone's typos."""
    cutoff = core.iso(
        core.utcnow() - timedelta(days=max(1.0, config.auth.attempt_retention_days))
    )
    db.purge_login_attempts(cutoff)


