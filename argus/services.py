# systemctl
# --------------------------------------------------------------------------


def _default_runner(argv: Sequence[str]) -> "subprocess.CompletedProcess[str]":
    return subprocess.run(list(argv), capture_output=True, text=True,
                          timeout=60, check=False)


def systemctl_available() -> bool:
    return shutil.which("systemctl") is not None


def _systemctl(runner: Runner, *args: str) -> "subprocess.CompletedProcess[str]":
    return runner(["systemctl", "--user", *args])


def linger_enabled(user: str | None = None, *, runner: Runner | None = None) -> bool | None:
    """Whether this user's services survive logout. None = cannot tell."""
    run = runner or _default_runner
    if shutil.which("loginctl") is None:
        return None
    name = user or os.environ.get("USER") or ""
    try:
        result = run(["loginctl", "show-user", name, "--property=Linger"])
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    return "Linger=yes" in (result.stdout or "")


def states(names: Sequence[str] = UNIT_NAMES, *,
           runner: Runner | None = None) -> dict[str, dict[str, str]]:
    """``systemctl --user show`` for each unit, as data.

    A unit that was never installed reports ``load_state=not-found``, which is
    a fact rather than an error — ``argus doctor`` prints it as "not installed"
    and moves on.
    """
    run = runner or _default_runner
    if not systemctl_available():
        return {name: {"load_state": "unknown", "active_state": "unknown",
                       "sub_state": "", "detail": "systemctl not found"}
                for name in names}
    out: dict[str, dict[str, str]] = {}
    for name in names:
        try:
            result = _systemctl(
                run, "show", name,
                # Result, not NRestarts, is what separates "stopped" from
                # "died": a unit that was restarted once an hour ago and then
                # stopped on purpose still reports NRestarts=1 forever.
                "--property=LoadState,ActiveState,SubState,UnitFileState,"
                "Result,ExecMainStatus,NRestarts",
            )
        except (OSError, subprocess.SubprocessError) as exc:
            out[name] = {"load_state": "unknown", "active_state": "unknown",
                         "sub_state": "", "detail": str(exc)}
            continue
        fields = dict(
            line.split("=", 1) for line in (result.stdout or "").splitlines() if "=" in line
        )
        out[name] = {
            "load_state": fields.get("LoadState", "unknown"),
            "active_state": fields.get("ActiveState", "unknown"),
            "sub_state": fields.get("SubState", ""),
            "unit_file_state": fields.get("UnitFileState", ""),
            "result": fields.get("Result", ""),
            "exit_status": fields.get("ExecMainStatus", ""),
            "restarts": fields.get("NRestarts", "0"),
        }
    return out


def control(action: str, names: Sequence[str], *, no_block: bool = True,
            runner: Runner | None = None) -> "subprocess.CompletedProcess[str]":
    """``systemctl --user <action> [--no-block] <names>`` — start/stop units.

    The seam the API uses to actuate a pause or a resume: it runs as the same
    user, so this is ``systemctl --user`` wrapped rather than shelled into, with
    the unit names built from module constants and never from a request.

    ``no_block`` is the default and it is load-bearing for resume. ``argus-vlm``
    is ``Type=forking`` and blocks its start until the model serves — minutes on
    a cold cache — so a blocking start would hang the caller for the whole load.
    ``--no-block`` hands the job to systemd and returns; readiness is then a
    health-poll question, not a held HTTP request.
    """
    if action not in ("start", "stop", "restart"):
        raise ServiceError(f"unsupported systemctl action: {action!r}")
    if not names:
        raise ServiceError("control() needs at least one unit")
    if not systemctl_available():
        raise ServiceError("systemctl not found — cannot start or stop units on this box")
    run = runner or _default_runner
    args = [action, *(["--no-block"] if no_block else []), *names]
    return _systemctl(run, *args)


