"""Account operations, and the rules that hold whoever performs them.

Between :mod:`argus.auth` (what a role means, what a hash is worth) and the two
callers that create accounts: the API's admin routes and ``argus user`` on the
box. Both must enforce the same three rules, so the rules live here rather than
twice:

* **The last enabled ADMIN cannot be disabled or demoted.** An appliance whose
  only administrator disabled themselves needs a person with shell access and a
  sqlite3 prompt to recover. That is a support call generated by a UI click.
* **A password change ends the account's sessions** (see
  ``Database.set_password``) — including, deliberately, the session of the admin
  who performed it on themselves. Being logged out is how a password change is
  supposed to feel.
* **Disabling ends them immediately.** "Disabled" that leaves an open browser
  working until its cookie expires is not disabled.

Failures are one exception type carrying an HTTP status, because the API needs a
status and the CLI needs a sentence, and deriving one from the other in two
places is how they drift.
"""

from __future__ import annotations

import sqlite3
from dataclasses import dataclass
from datetime import timedelta
from typing import Any, NoReturn

from argus import auth as core
from argus.config import ArgusConfig
from argus.db import Database, Row


class AccountError(Exception):
    """Something an operator did that cannot be done, with the reason.

    ``status`` is the HTTP code the API should answer with; the CLI prints
    ``str(exc)`` and ignores it.
    """

    def __init__(self, message: str, *, status: int = 400):
        super().__init__(message)
        self.status = status


# --------------------------------------------------------------------------
# creating and editing accounts
# --------------------------------------------------------------------------


def create_user(db: Database, username: str, password: str, *, role: str,
                display_name: str | None = None) -> Row:
    try:
        username = core.normalize_username(username)
        role = core.normalize_role(role)
    except ValueError as exc:
        raise AccountError(str(exc), status=422) from exc
    try:
        password_hash = core.hash_password(password)
    except core.PasswordError as exc:
        raise AccountError(str(exc), status=422) from exc

    label = (display_name or "").strip() or username
    try:
        user_id = db.create_user(username, label, role, password_hash)
    except sqlite3.IntegrityError as exc:
        raise AccountError(f"user already exists: {username}", status=409) from exc
    created = db.get_user(user_id)
    assert created is not None  # just inserted
    return created


def set_password(db: Database, user_id: int, password: str) -> Row:
    user = _require_user(db, user_id)
    try:
        password_hash = core.hash_password(password)
    except core.PasswordError as exc:
        raise AccountError(str(exc), status=422) from exc
    db.set_password(user_id, password_hash)
    refreshed = db.get_user(user_id)
    return refreshed if refreshed is not None else user


def set_role(db: Database, user_id: int, role: str) -> Row:
    user = _require_user(db, user_id)
    try:
        role = core.normalize_role(role)
    except ValueError as exc:
        raise AccountError(str(exc), status=422) from exc
    if user["role"] == "ADMIN" and role != "ADMIN":
        _refuse_if_last_admin(db, user_id, verb="change the role of")
    db.update_user(user_id, role=role)
    # A demotion must not leave the browser holding the old authority. The
    # session row carries no role — it joins to `users` on every request — so
    # this is belt and braces, but it also makes the console re-render as the
    # new role immediately rather than at the next 403.
    if user["role"] != role:
        db.delete_sessions_for_user(user_id)
    refreshed = db.get_user(user_id)
    return refreshed if refreshed is not None else user


def set_disabled(db: Database, user_id: int, disabled: bool) -> Row:
    user = _require_user(db, user_id)
    if disabled and user["role"] == "ADMIN":
        _refuse_if_last_admin(db, user_id, verb="disable")
    db.update_user(user_id, disabled=1 if disabled else 0)
    if disabled:
        db.delete_sessions_for_user(user_id)
    refreshed = db.get_user(user_id)
    return refreshed if refreshed is not None else user


def rename(db: Database, user_id: int, display_name: str) -> Row:
    _require_user(db, user_id)
    label = str(display_name).strip()
    if not label:
        raise AccountError("display name must not be empty", status=422)
    db.update_user(user_id, display_name=label)
    refreshed = db.get_user(user_id)
    assert refreshed is not None
    return refreshed


def _require_user(db: Database, user_id: int) -> Row:
    user = db.get_user(user_id)
    if user is None:
        raise AccountError(f"user not found: {user_id}", status=404)
    return user


def _refuse_if_last_admin(db: Database, user_id: int, *, verb: str) -> None:
    """Guard the bootstrap. Counts *enabled* admins other than this one."""
    others = [
        row for row in db.list_users(include_disabled=False)
        if row["role"] == "ADMIN" and int(row["id"]) != int(user_id)
    ]
    if not others:
        raise AccountError(
            f"cannot {verb} the only enabled ADMIN — create another administrator first",
            status=409,
        )


def user_by_name(db: Database, username: str) -> Row:
    try:
        normalized = core.normalize_username(username)
    except ValueError as exc:
        raise AccountError(str(exc), status=422) from exc
    user = db.get_user_by_username(normalized)
    if user is None:
        raise AccountError(f"user not found: {normalized}", status=404)
    return user


